#include <bits/stdc++.h>
using namespace std;

int dp[52][52][1253] = {0};     // dp[i][j][k]: 考虑到第i列，第i列选了j块，总共k块的最大值
int maxn[52][52][1253];          // maxn[i][j][k]: 考虑到第i列，第i列至少选j块，总共k块的最大值
int n, m;
int num[52][52];                 // 原始输入
int sum[52][52];                 // sum[i][j]: 第j列前i行的前缀和

int main() {
    cin >> n >> m;
    
    // 读入原始三角形（按行读入）
    for(int i = 1; i <= n; i++) {
        for(int j = 1; j <= n - i + 1; j++) {
            cin >> num[i][j];
        }
    }
    
    // ========== 关键步骤1：坐标变换（旋转90度） ==========
    // 原三角形：
    //   第1行：a11 a12 a13 ... a1n
    //   第2行：a21 a22 ... a2(n-1)
    //   ...
    // 变换后成为列对齐的直角三角形：
    //   第1列：a11, a21, a31, ..., an1
    //   第2列：a12, a22, a32, ...
    //   第3列：a13, a23, ...
    //   ...
    // 这样变换后，敲砖规则变为：要选第i行第j列，必须选第i-1行第j-1列和第i-1行第j列
    
    // 计算变换后每列的前缀和
    // sum[i][j] 表示第j列前i行的和（i从1到n-j+1）
    for(int j = 1; j <= n; j++) {              // 枚举列
        for(int i = 1; i <= n - j + 1; i++) {  // 枚举行（该列的有效行数）
            // 变换：原第i行第j列 -> 新第j列第i行
            // 但这里我们直接按列累加
            sum[i][j] = sum[i-1][j] + num[i][j];
        }
    }
    
    // ========== 关键步骤2：初始化 ==========
    memset(maxn, -1, sizeof(maxn));   // -1表示不可达状态
    for(int i = 0; i <= m; i++) {
        maxn[0][0][i] = 0;            // 0列，选0块，总砖数i，价值为0（边界）
    }
    
    // ========== 关键步骤3：动态规划 ==========
    // 状态定义：
    // dp[i][j][k]: 考虑到第i列，第i列选了j块砖，总共选了k块砖的最大价值
    // maxn[i][j][k]: max(dp[i][t][k])，其中 t >= j
    // 
    // 转移方程：
    // 当前列选了j块，那么上一列必须至少选j-1块（因为依赖关系）
    // dp[i][j][k] = maxn[i-1][max(0,j-1)][k-j] + sum[j][i]
    // 其中 sum[j][i] 是第i列前j块的和
    
    for(int i = 1; i <= n; i++) {              // 枚举当前列
        // j从大到小枚举，方便维护maxn数组
        // j的最大值是 n-i+1（该列的最大行数）
        for(int j = n - i + 1; j >= 0; j--) {  
            for(int k = j; k <= m; k++) {      // 总砖数至少为当前列选的砖数
                // 从上一列转移
                if(maxn[i-1][max(0, j-1)][k-j] >= 0) {
                    // 当前价值 = 前面列的最优值 + 当前列前j块的和
                    dp[i][j][k] = maxn[i-1][max(0, j-1)][k-j] + sum[j][i];
                    
                    // 更新maxn：当前列至少选j块的最大值
                    // = max(至少选j-1块, 恰好选j块)
                    maxn[i][j][k] = max(maxn[i][j-1][k], dp[i][j][k]);
                }
            }
        }
    }
    
    // ========== 关键步骤4：统计答案 ==========
    int ans = -1;
    for(int i = 1; i <= n; i++) {          // 枚举最后一列
        for(int j = 0; j <= n - i + 1; j++) {  // 枚举最后一列选的块数
            ans = max(ans, dp[i][j][m]);   // 取总砖数为m的最大值
        }
    }
    
    cout << ans << endl;
    return 0;
}